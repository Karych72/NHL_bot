    "<b>USAT %</b> — доля <i>не заблокированных</i> попыток броска (семейство Fenwick, без блоков). "
    "Интерпретация близка к SAT %, но метрика ближе к событиям, дошедшим до вратаря или сетки.\n\n"
    "<b>GF %</b> (Goals For %) — доля голов «за» от суммы голов «за» и «против» при игре игрока на льду. "
    "Это именно результат в воротах, а не объём бросков; расхождения с SAT/USAT часто связаны "
    "с реализацией и игрой вратарей.\n\n"
    "В меню <code>/advanced</code> также есть <b>OZ Start %</b> (доля вбрасываний в зоне атаки), "

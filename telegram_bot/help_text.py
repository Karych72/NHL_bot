def _command_items(commands: Sequence[CommandSpec]) -> List[str]:
    """Строки `/команда — описание (уточнение)` списка команд в `/help`."""
    return [
        f"/{c.name} — {c.description}"
        + (f" ({_COMMAND_DETAILS[c.name]})" if c.name in _COMMAND_DETAILS else "")
        for c in commands
    ]



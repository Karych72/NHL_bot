# Подробно про SAT/USAT/GF % — дублируется в ответе /advanced и в /help.
ADVANCED_STATS_EXPLAINED = (
    "*SAT %*, *USAT %*, *GF %* — что означают\n\n"
    "*SAT %* — в данных NHL и в боте это доля всех *попыток броска* (семейство Corsi): голы, "
    "броски в створ, промахи и заблокированные броски «за» и «против», пока игрок на льду. "
    "Считается как доля попыток команды игрока от суммы «за» и «против». Выше 50% обычно значит, "
    "что при выходе игрока команда чаще давит в атаке, чем терпит давление в обороне.\n\n"
    "*USAT %* — доля *не заблокированных* попыток броска (семейство Fenwick, без блоков). "
    "Интерпретация близка к SAT %, но метрика ближе к событиям, дошедшим до вратаря или сетки.\n\n"
    "*GF %* (Goals For %) — доля голов «за» от суммы голов «за» и «против» при игре игрока на льду. "
    "Это именно результат в воротах, а не объём бросков; расхождения с SAT/USAT часто связаны "
    "с реализацией и игрой вратарей.\n\n"
    "В меню `/advanced` также есть *OZ Start %* (доля вбрасываний в зоне атаки), "
    "*Shootout %* (реализация буллитов за сезон) и *голы по типам броска* "
    "(кистевой, щелчок, с полуприёма и т.д.)."
)


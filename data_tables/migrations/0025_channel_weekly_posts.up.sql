-- Миграция 0025: отметки еженедельных постов в Telegram-канал (Задача 120) — день × вид поста
-- (турнирная таблица в субботу, лучшие игроки России в воскресенье, 18:00 МСК). Отметка не даёт
-- прогонам sync после 18:00 повторить пост и позволяет догнать его, если слот 18:00 сорвался.
-- Только миграция, без data_tables/t.*.sql: отметки не восстановить повторной загрузкой.

CREATE TABLE bot_channel_weekly_posts (
    day DATE NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('standings', 'country')),
    PRIMARY KEY (day, kind)
);
